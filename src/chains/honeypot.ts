/**
 * Honeypot test for PulseChain tokens: a simulated buy and sell.
 *
 * contracts/SellSimulator.sol is placed at a throwaway address inside a
 * read-only eth_call (a state override, so nothing touches the real chain),
 * given some PLS there, and asked to buy the token through PulseX and sell it
 * straight back. A sell that fails outright means holders can't get out.
 *
 * Taxes: the buy tax is the gap between tokens that left the pool and tokens
 * that arrived. The sell tax works back from the PLS actually received through
 * the pool's constant-product formula (reserves before the sale, with the fee
 * implied by the router's own quote) to how many tokens effectively reached the
 * pool. That is exact under price impact, and counts tokens that dump their own
 * tax stash into the pool during a sale as the cost to the seller it is.
 * Checked against rigged tokens (a blocked sell, an exact 25% tax) built and
 * traded inside one simulated call.
 *
 * Mainstream honeypot scanners don't cover PulseChain, so this is the only
 * such check there. Both PulseX routers are tried; tokens with no PLS pool
 * can't be tested this way.
 */

