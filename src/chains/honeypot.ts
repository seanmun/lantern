const SIMULATOR = '0x000000000000000000000000000000000000Ba5e';
const WPLS = '0xA1077a294dDE1B09bB078844df40758a5D0f9a27';
const ROUTERS = [
  '0x165C3410fC91EF562C50559f7d2289fEbed552d9', // PulseX V2
  '0x98bf93ebf5c380C0e6Ae8e192A7e2AE08edAcc02', // PulseX V1
];
const TEST_AMOUNT = ethers.parseEther('200000'); // about a dollar of PLS: enough to measure, small enough for thin pools
const GAS = ethers.toQuantity(30_000_000);

const sim = new ethers.Interface([
  'function run(address router, address wrapped, address token, uint256 amountIn) returns (tuple(uint8 stage, uint256 buySent, uint256 buyGot, uint256 sellSent, uint256 sellQuote, uint256 sellReceived, uint256 reserveToken, uint256 reserveWrapped))',
]);

export type TradeOutcome = 'ok' | 'no-pool' | 'buy-failed' | 'approve-failed' | 'sell-failed';

export interface TradeSimulation {
  outcome: TradeOutcome;
  buyTax: number | null;  // 0..1, share lost on the way in beyond normal pool fees
  sellTax: number | null; // 0..1, share lost on the way out
  router: string | null;
}

const OUTCOMES: TradeOutcome[] = ['ok', 'no-pool', 'buy-failed', 'approve-failed', 'sell-failed'];
const clamp = (v: number) => Math.min(1, Math.max(0, v));

interface Raw { stage: bigint; buySent: bigint; buyGot: bigint; sellSent: bigint; sellQuote: bigint; sellReceived: bigint; reserveToken: bigint; reserveWrapped: bigint }

function buyTaxOf(r: Raw): number | null {
  return r.buySent > BigInt(0) ? clamp(1 - Number(r.buyGot) / Number(r.buySent)) : null;
}

function sellTaxOf(r: Raw): number | null {
  const [S, Q, G, Rt, Rw] = [r.sellSent, r.sellQuote, r.sellReceived, r.reserveToken, r.reserveWrapped].map(Number);
  if (!(S > 0 && Q > 0 && Rt > 0 && Rw > Q && Rw > G)) return null;
  const fee = (Q * Rt) / (S * (Rw - Q));           // fee factor implied by the router's quote
  const effective = (G * Rt) / (fee * (Rw - G));   // tokens that would return the PLS actually received
  return clamp(1 - effective / S);
}

async function runOn(provider: ethers.JsonRpcProvider, router: string, token: string): Promise<TradeSimulation> {
  const data = sim.encodeFunctionData('run', [router, WPLS, token, TEST_AMOUNT]);
  const raw = await provider.send('eth_call', [
    { from: SIMULATOR, to: SIMULATOR, data, gas: GAS },
    'latest',
    { [SIMULATOR]: { code: SIMULATOR_CODE, balance: ethers.toQuantity(TEST_AMOUNT * BigInt(2)) } },
  ]);
  const r = sim.decodeFunctionResult('run', raw)[0] as unknown as Raw;
  const outcome = OUTCOMES[Number(r.stage)] ?? 'buy-failed';
  return {
    outcome,
    buyTax: outcome === 'no-pool' || outcome === 'buy-failed' ? null : buyTaxOf(r),
    sellTax: outcome === 'ok' ? sellTaxOf(r) : null,
    router,
  };
}

/** Buy-and-sell simulation on PulseX; prefers a router where the round trip completes. */
export async function simulateTrade(token: string): Promise<TradeSimulation> {
  const provider = createProvider(PULSECHAIN_CONFIG);
  const results = await Promise.all(ROUTERS.map((r) => runOn(provider, r, token).catch(() => null)));
  const valid = results.filter((r): r is TradeSimulation => r !== null);
  const ok = valid.find((r) => r.outcome === 'ok');
  if (ok) return ok;
  // No clean round trip: report the most telling failure among routers that have a pool
  const order: TradeOutcome[] = ['sell-failed', 'approve-failed', 'buy-failed', 'no-pool'];
  for (const o of order) {
    const hit = valid.find((r) => r.outcome === o);
    if (hit) return hit;
  }
  return { outcome: 'no-pool', buyTax: null, sellTax: null, router: null };
}
